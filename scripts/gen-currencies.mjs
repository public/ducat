#!/usr/bin/env node
// Generates src/generated/*.ts from the snapshots in data/.
//
//   node scripts/gen-currencies.mjs           regenerate the tables
//   node scripts/gen-currencies.mjs --check   exit 1 if the committed tables are stale (CI)
//   node scripts/gen-currencies.mjs --fetch   also download the live ISO 4217 list from SIX
//                                             and report differences against the snapshot
//
// Sources (see README "Currency data"):
//   data/iso4217-list-one.xml  ISO 4217 List One, SIX Group (maintenance agency)
//   data/stripe.json           curated from https://docs.stripe.com/currencies
//   data/adyen.json            curated from https://docs.adyen.com/development-resources/currency-codes
//   data/cash-rounding.json    curated cash-rounding rules with sources
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');
const args = new Set(process.argv.slice(2));
const SIX_URL =
  'https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml';

export function parseIsoXml(xml) {
  const published = /Pblshd="([^"]+)"/.exec(xml)?.[1];
  const entries = new Map();
  for (const m of xml.matchAll(/<CcyNtry>([\s\S]*?)<\/CcyNtry>/g)) {
    const body = m[1];
    const code = /<Ccy>([A-Z]{3})<\/Ccy>/.exec(body)?.[1];
    if (!code) continue; // e.g. ANTARCTICA: no universal currency
    const units = /<CcyMnrUnts>([^<]+)<\/CcyMnrUnts>/.exec(body)?.[1];
    const numeric = /<CcyNbr>(\d+)<\/CcyNbr>/.exec(body)?.[1];
    const name = /<CcyNm[^>]*>([^<]+)<\/CcyNm>/.exec(body)?.[1];
    const country = /<CtryNm>([^<]+)<\/CtryNm>/.exec(body)?.[1];
    const exponent = units === 'N.A.' ? null : Number(units);
    const prev = entries.get(code);
    if (prev && prev.exponent !== exponent) throw new Error(`inconsistent exponent for ${code}`);
    const e = prev ?? { code, numeric, name, exponent, countries: [] };
    e.countries.push(country);
    entries.set(code, e);
  }
  return { published, entries };
}

const header = (src) =>
  `// GENERATED by scripts/gen-currencies.mjs from ${src}. Do not edit by hand.\n/* eslint-disable */\n`;

/**
 * Packs ISO codes and exponents into one short string that gzips far better than an object literal:
 * 26 space-separated groups (A to Z), each listing the last two letters of its codes, followed by the
 * exponent digit when it is not 2. "EDFN BHD3" would be AED, AFN, BHD (exponent 3).
 */
function packIsoExponents(iso) {
  const groups = Array.from({ length: 26 }, () => '');
  for (const [code, exponent] of Object.entries(iso)) {
    if (!/^[A-Z]{3}$/.test(code) || !Number.isInteger(exponent) || exponent < 0 || exponent > 9) {
      throw new Error(`cannot pack ${code}: ${exponent}`);
    }
    groups[code.charCodeAt(0) - 65] += code.slice(1) + (exponent === 2 ? '' : String(exponent));
  }
  return groups.join(' ');
}

/** The decoder emitted into src/generated/iso4217.ts; the generator runs the same code to verify the packing. */
const UNPACK_SOURCE = `function unpackIsoExponents(packed: string): Record<string, number> {
  const exponents: Record<string, number> = {};
  for (const [letter, group] of packed.split(' ').entries()) {
    for (let i = 0; i < group.length; i += 2) {
      const code = String.fromCharCode(65 + letter) + group.slice(i, i + 2);
      const next = group.charCodeAt(i + 2);
      const hasExponent = next >= 48 && next <= 57;
      exponents[code] = hasExponent ? next - 48 : 2;
      if (hasExponent) {
        i++;
      }
    }
  }
  return exponents;
}`;

// The same decoder as plain JavaScript (only the TypeScript signature and the one annotation differ),
// so generation fails if the emitted code would not reproduce the table.
const unpackIsoExponents = new Function(
  'packed',
  UNPACK_SOURCE.slice(UNPACK_SOURCE.indexOf('{') + 1, -1).replace(': Record<string, number> = {}', ' = {}'),
);

/** Fails generation unless `actual` has exactly the entries of `expected` (order ignored). */
function assertSameTable(name, actual, expected) {
  const a = JSON.stringify(Object.entries(actual).sort());
  const e = JSON.stringify(Object.entries(expected).sort());
  if (a !== e) throw new Error(`${name}: the compact encoding does not reproduce the table`);
}

/**
 * Describes a processor table relative to the ISO table, which the core ships anyway: the ISO codes it
 * leaves out, and every entry that differs from `fromIso(isoExponent)` or is not an ISO code at all.
 */
function diffAgainstIso(table, iso, fromIso) {
  const missing = Object.keys(iso).filter((code) => !(code in table));
  const overrides = {};
  for (const [code, value] of Object.entries(table)) {
    if (!(code in iso) || JSON.stringify(value) !== JSON.stringify(fromIso(iso[code]))) overrides[code] = value;
  }
  const rebuilt = {};
  for (const code of Object.keys(iso)) if (!missing.includes(code)) rebuilt[code] = fromIso(iso[code]);
  Object.assign(rebuilt, overrides);
  return { missing, overrides, rebuilt };
}

const inlineObj = (o) =>
  '{ ' +
  Object.entries(o)
    .map(([k, v]) => `${k}: ${JSON.stringify(v)}`)
    .join(', ') +
  ' }';

function generate() {
  const { published, entries } = parseIsoXml(read('data/iso4217-list-one.xml'));
  const iso = {};
  const nonMonetary = [];
  for (const e of [...entries.values()].sort((a, b) => (a.code < b.code ? -1 : 1))) {
    if (e.exponent === null) nonMonetary.push(e.code);
    else iso[e.code] = e.exponent;
  }
  const out = {};
  const packed = packIsoExponents(iso);
  assertSameTable('ISO 4217', unpackIsoExponents(packed), iso);
  const codes = Object.keys(iso);
  out['iso4217.ts'] =
    header('data/iso4217-list-one.xml') +
    `\n/** Publication date of the ISO 4217 List One snapshot the table was generated from. */\n` +
    `export const ISO_4217_PUBLISHED = ${JSON.stringify(published)};\n\n` +
    `/** An active ISO 4217 code with a minor unit (${codes.length} codes). */\n` +
    `export type IsoCurrencyCode =\n${codes.map((c) => `  | ${JSON.stringify(c)}`).join('\n')};\n\n` +
    `/**\n * The ISO table packed for size: 26 space-separated groups (A to Z), each listing the last two letters\n` +
    ` * of its codes, followed by the exponent when it is not 2.\n */\n` +
    `const PACKED = ${JSON.stringify(packed)};\n\n` +
    `/** ISO 4217 minor-unit exponent for every active code that has one. */\n` +
    `export const ISO_EXPONENTS: Readonly<Record<IsoCurrencyCode, number>> = /* @__PURE__ */ unpackIsoExponents(PACKED);\n\n` +
    UNPACK_SOURCE +
    `\n\n/** Active codes whose minor unit is "N.A." (precious metals, SDR, testing): not monetary, not in ISO_EXPONENTS. */\n` +
    `export const ISO_NON_MONETARY = ${JSON.stringify(nonMonetary)} as const;\n`;

  // Stripe: [exponent the API expects, multiple the charge amount must be, multiple a payout amount must be]
  const s = JSON.parse(read('data/stripe.json'));
  const stripe = {};
  for (const code of [...s.presentment].sort()) {
    let e = s.defaultExponent;
    let charge = 1;
    let payout = 1;
    if (s.zeroDecimal.includes(code)) e = 0;
    if (s.threeDecimal.includes(code)) {
      e = 3;
      charge = 10;
      payout = 10;
    }
    const sc = s.specialCases[code];
    if (sc) {
      e = sc.apiExponent;
      if (code === 'ISK' || code === 'UGX') {
        charge = 100;
        payout = 100;
      }
      if (code === 'HUF' || code === 'TWD') payout = 100;
    }
    stripe[code] = [e, charge, payout];
  }
  const stripeDiff = diffAgainstIso(stripe, iso, (exponent) => [exponent, 1, 1]);
  assertSameTable('Stripe', stripeDiff.rebuilt, stripe);
  out['stripe.ts'] =
    header('data/stripe.json (https://docs.stripe.com/currencies, retrieved ' + s.retrieved + ')') +
    `import { ISO_EXPONENTS } from './iso4217.js';\n` +
    `\n/**\n * Stripe presentment currencies: [API exponent, charge amount multiple, payout amount multiple].\n` +
    ` * A multiple of 100 means "send a two-decimal value whose decimal part is always 00" (ISK, UGX)\n` +
    ` * or, for payouts only, whole units (HUF, TWD). A multiple of 10 is the three-decimal rule\n` +
    ` * (last digit must be 0).\n *\n` +
    ` * Stored relative to the ISO table, which the core ships anyway: every ISO code is [ISO exponent, 1, 1]\n` +
    ` * except the ones Stripe does not list, and the overrides below.\n */\n` +
    `export const STRIPE_RULES: Readonly<Record<string, readonly [exponent: number, chargeMultiple: number, payoutMultiple: number]>> =\n` +
    `  /* @__PURE__ */ fromIso(${JSON.stringify(stripeDiff.missing.join(' '))}, ${inlineObj(stripeDiff.overrides)});\n\n` +
    `function fromIso(\n  notListed: string,\n  overrides: Record<string, readonly [number, number, number]>,\n): Record<string, readonly [number, number, number]> {\n` +
    `  const rules: Record<string, readonly [number, number, number]> = {};\n` +
    `  const skip = new Set(notListed.split(' '));\n` +
    `  for (const [code, exponent] of Object.entries(ISO_EXPONENTS)) {\n` +
    `    if (!skip.has(code)) {\n      rules[code] = [exponent, 1, 1];\n    }\n  }\n` +
    `  return Object.assign(rules, overrides);\n}\n`;

  const a = JSON.parse(read('data/adyen.json'));
  const adyenDiff = diffAgainstIso(a.exponents, iso, (exponent) => exponent);
  assertSameTable('Adyen', adyenDiff.rebuilt, a.exponents);
  out['adyen.ts'] =
    header('data/adyen.json (' + a.source + ', retrieved ' + a.retrieved + ')') +
    `import { ISO_EXPONENTS } from './iso4217.js';\n` +
    `\n/**\n * Adyen minor-unit exponents (Adyen's table is authoritative where it differs from ISO: CLP, CVE, IDR, ISK).\n` +
    ` * Stored relative to the ISO table, which the core ships anyway: every ISO code except the ones Adyen does\n` +
    ` * not list, with the overrides below.\n */\n` +
    `export const ADYEN_EXPONENTS: Readonly<Record<string, number>> = /* @__PURE__ */ fromIso(\n` +
    `  ${JSON.stringify(adyenDiff.missing.join(' '))},\n  ${inlineObj(adyenDiff.overrides)},\n);\n\n` +
    `function fromIso(notListed: string, overrides: Record<string, number>): Record<string, number> {\n` +
    `  const exponents: Record<string, number> = {};\n` +
    `  const skip = new Set(notListed.split(' '));\n` +
    `  for (const [code, exponent] of Object.entries(ISO_EXPONENTS)) {\n` +
    `    if (!skip.has(code)) {\n      exponents[code] = exponent;\n    }\n  }\n` +
    `  return Object.assign(exponents, overrides);\n}\n`;

  const c = JSON.parse(read('data/cash-rounding.json'));
  const rules = c.rules.map((r) => {
    const exp = iso[r.currency];
    const [i, f = ''] = r.increment.split('.');
    if (f.length > exp) throw new Error(`cash increment ${r.increment} finer than ${r.currency} exponent`);
    const minor = Number(i + f.padEnd(exp, '0'));
    return {
      currency: r.currency,
      increment: minor,
      countries: r.countries,
      scope: r.scope,
      verified: r.verified,
      source: r.source,
    };
  });
  out['cash.ts'] =
    header('data/cash-rounding.json') +
    `\nexport interface CashRule {\n  readonly currency: string;\n  /** Smallest cash step, in ISO minor units. */\n  readonly increment: number;\n  readonly countries: readonly string[];\n  readonly scope: string;\n  /** false: only secondary sources were found. */\n  readonly verified: boolean;\n  readonly source: string;\n}\n\n` +
    `export const CASH_RULES: readonly CashRule[] = ${JSON.stringify(rules, null, 2)};\n`;
  return { out, entries, published };
}

const { out, entries, published } = generate();
const dir = join(root, 'src/generated');
let stale = false;
for (const [name, text] of Object.entries(out)) {
  const p = join(dir, name);
  let cur = null;
  try {
    cur = readFileSync(p, 'utf8');
  } catch {}
  if (cur !== text) {
    stale = true;
    if (!args.has('--check')) {
      mkdirSync(dir, { recursive: true });
      writeFileSync(p, text);
      console.log('wrote', p);
    }
  }
}
if (args.has('--check')) {
  if (stale) {
    console.error('src/generated is stale: run node scripts/gen-currencies.mjs');
    process.exit(1);
  }
  console.log('src/generated is up to date (ISO 4217 published ' + published + ')');
}
if (args.has('--fetch')) {
  const live = parseIsoXml(await (await fetch(SIX_URL)).text());
  const diffs = [];
  for (const [code, e] of live.entries) {
    const old = entries.get(code);
    if (!old) diffs.push(`+ ${code} (exponent ${e.exponent}) added`);
    else if (old.exponent !== e.exponent) diffs.push(`~ ${code} exponent ${old.exponent} -> ${e.exponent}`);
  }
  for (const code of entries.keys()) if (!live.entries.has(code)) diffs.push(`- ${code} withdrawn`);
  console.log(`live ISO 4217 list published ${live.published}; snapshot ${published}`);
  console.log(diffs.length ? diffs.join('\n') : 'no differences');
  if (diffs.length) process.exitCode = 2;
}
