#!/usr/bin/env node
// Generates src/generated/*.ts from the snapshots in data/.
//
//   node scripts/gen-currencies.mjs           regenerate the tables
//   node scripts/gen-currencies.mjs --check   exit 1 if the committed tables are stale (CI)
//   node scripts/gen-currencies.mjs --fetch   also download the live ISO 4217 list from SIX
//                                             and report differences against the snapshot
//
// Sources (see README "Currency data"):
//   data/iso4217-list-one.xml  ISO 4217 List One, SIX Group (maintenance agency)
//   data/stripe.json           curated from https://docs.stripe.com/currencies
//   data/adyen.json            curated from https://docs.adyen.com/development-resources/currency-codes
//   data/cash-rounding.json    curated cash-rounding rules with sources
//   data/<processor>.json      one file per further processor (checkout, ...), same shape:
//                              currencies, defaultExponent (a number or "iso"), exponents and
//                              multiples overrides, quoted sources with retrieval dates
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (path) => readFileSync(join(root, path), 'utf8');
const args = new Set(process.argv.slice(2));
const SIX_URL =
  'https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml';

export function parseIsoXml(xml) {
  const published = /Pblshd="([^"]+)"/.exec(xml)?.[1];
  const entries = new Map();
  for (const match of xml.matchAll(/<CcyNtry>([\s\S]*?)<\/CcyNtry>/g)) {
    const body = match[1];
    const code = /<Ccy>([A-Z]{3})<\/Ccy>/.exec(body)?.[1];
    // e.g. ANTARCTICA: no universal currency
    if (!code) {
      continue;
    }
    const units = /<CcyMnrUnts>([^<]+)<\/CcyMnrUnts>/.exec(body)?.[1];
    const numeric = /<CcyNbr>(\d+)<\/CcyNbr>/.exec(body)?.[1];
    const name = /<CcyNm[^>]*>([^<]+)<\/CcyNm>/.exec(body)?.[1];
    const country = /<CtryNm>([^<]+)<\/CtryNm>/.exec(body)?.[1];
    const exponent = units === 'N.A.' ? null : Number(units);
    const prev = entries.get(code);
    if (prev && prev.exponent !== exponent) {
      throw new Error(`inconsistent exponent for ${code}`);
    }
    const entry = prev ?? { code, numeric, name, exponent, countries: [] };
    entry.countries.push(country);
    entries.set(code, entry);
  }
  return { published, entries };
}

const header = (src) =>
  `// GENERATED by scripts/gen-currencies.mjs from ${src}. Do not edit by hand.\n/* eslint-disable */\n`;
const obj = (object) =>
  '{\n' +
  Object.entries(object)
    .map(([key, value]) => `  ${key}: ${JSON.stringify(value)},`)
    .join('\n') +
  '\n}';

// Further processors: `extra` lists per-context multiple overrides; without `multiples` in the data
// file the table is just exponents.
const PROCESSORS = [
  {
    file: 'checkout',
    name: 'CHECKOUT_RULES',
    extra: ['standaloneMultiples'],
    doc: 'Checkout.com currencies: [API exponent, payment amount multiple, Standalone API (authentication) multiple]. CLP is two-decimal with a multiple of 100; three-decimal currencies need a multiple of 10.',
  },
  {
    file: 'paypal',
    name: 'PAYPAL_EXPONENTS',
    doc: 'PayPal decimals per currency (`value` is a decimal string). HUF, JPY and TWD take none.',
  },
  {
    file: 'braintree',
    name: 'BRAINTREE_EXPONENTS',
    doc: 'Braintree decimals per currency (`amount` is a decimal string). The zero-decimal list includes LAK (ISO 2).',
  },
  {
    file: 'klarna',
    name: 'KLARNA_EXPONENTS',
    doc: 'Klarna purchase currencies and their ISO 4217 exponents (amounts are integer minor units).',
  },
];

/**
 * Packs ISO codes and exponents into one short string: 26 space-separated groups (A to Z), each
 * listing the last two letters of its codes, followed by the exponent digit when it is not 2. "EDFN
 * BHD3" is AED, AFN, BHD (exponent 3). It gzips smaller than the object literal it replaces.
 */
function packIsoExponents(iso) {
  const groups = Array.from({ length: 26 }, () => '');
  for (const [code, exponent] of Object.entries(iso)) {
    if (!/^[A-Z]{3}$/.test(code) || !Number.isInteger(exponent) || exponent < 0 || exponent > 9) {
      throw new Error(`cannot pack ${code}: ${exponent}`);
    }
    const exponentDigit = exponent === 2 ? '' : String(exponent);
    groups[code.charCodeAt(0) - 65] += code.slice(1) + exponentDigit;
  }
  return groups.join(' ');
}

// The decoder emitted into src/generated/iso4217.ts. The generator runs the same code (below) to
// check that the packed string decodes to exactly the ISO table.
const UNPACK_SOURCE = `function unpackIsoExponents(packed: string): Record<string, number> {
  const exponents: Record<string, number> = {};
  for (const [letter, group] of packed.split(' ').entries()) {
    for (let i = 0; i < group.length; i += 2) {
      const code = String.fromCharCode(65 + letter) + group.slice(i, i + 2);
      const next = group.charCodeAt(i + 2);
      const hasExponent = next >= 48 && next <= 57;
      exponents[code] = hasExponent ? next - 48 : 2;
      if (hasExponent) {
        i++;
      }
    }
  }
  // An object built key by key is a slow hash table in V8, while lookups with one constant code
  // (money('1', 'EUR')) are fastest on an object literal. Using the table as a prototype makes V8
  // turn it into a fast object like a literal; other engines are unaffected.
  function UseAsPrototype() {}
  UseAsPrototype.prototype = exponents;
  return exponents;
}`;

// The same decoder as plain JavaScript (only the signature and one annotation differ).
const unpackIsoExponents = new Function(
  'packed',
  UNPACK_SOURCE.slice(UNPACK_SOURCE.indexOf('{') + 1, -1).replace(
    ': Record<string, number> = {}',
    ' = {}',
  ),
);

/**
 * Source for an exponent table stored relative to the ISO table, which every bundle ships anyway:
 * the ISO codes the table leaves out, plus the entries that differ from ISO or are not ISO codes.
 * Returns null when listing the table in full would be shorter. The generator rebuilds the table
 * from that description and fails unless it matches exactly.
 */
function isoRelativeExponents(name, table, iso) {
  const notListed = Object.keys(iso).filter((code) => !(code in table));
  const overrides = {};
  for (const [code, exponent] of Object.entries(table)) {
    if (iso[code] !== exponent) {
      overrides[code] = exponent;
    }
  }
  if (notListed.length + Object.keys(overrides).length > Object.keys(table).length / 2) {
    return null;
  }
  const rebuilt = {};
  for (const [code, exponent] of Object.entries(iso)) {
    if (!notListed.includes(code)) {
      rebuilt[code] = exponent;
    }
  }
  Object.assign(rebuilt, overrides);
  if (
    JSON.stringify(Object.entries(rebuilt).sort()) !== JSON.stringify(Object.entries(table).sort())
  ) {
    throw new Error(`${name}: the ISO-relative form does not rebuild the table`);
  }
  const overridesSource = Object.entries(overrides)
    .map(([code, exponent]) => `${code}: ${exponent}`)
    .join(', ');
  return (
    `/* @__PURE__ */ exponentsFromIso(\n  ${JSON.stringify(notListed.join(' '))},\n  { ${overridesSource} },\n);\n\n` +
    `/** The ISO exponents, without the codes in \`notListed\`, with \`overrides\` applied. */\n` +
    `function exponentsFromIso(notListed: string, overrides: Record<string, number>): Record<string, number> {\n` +
    `  const skip = new Set(notListed.split(' '));\n` +
    `  const exponents: Record<string, number> = {};\n` +
    `  for (const [code, exponent] of Object.entries(ISO_EXPONENTS)) {\n` +
    `    if (!skip.has(code)) {\n      exponents[code] = exponent;\n    }\n  }\n` +
    `  Object.assign(exponents, overrides);\n` +
    `  // As in iso4217.ts: using the table as a prototype makes V8 turn it into a fast object.\n` +
    `  function UseAsPrototype() {}\n  UseAsPrototype.prototype = exponents;\n  return exponents;\n}\n`
  );
}

function generate() {
  const { published, entries } = parseIsoXml(read('data/iso4217-list-one.xml'));
  const iso = {};
  const nonMonetary = [];
  for (const entry of [...entries.values()].sort((left, right) =>
    left.code < right.code ? -1 : 1,
  )) {
    if (entry.exponent === null) {
      nonMonetary.push(entry.code);
    } else {
      iso[entry.code] = entry.exponent;
    }
  }
  const out = {};
  const packed = packIsoExponents(iso);
  const unpacked = unpackIsoExponents(packed);
  if (
    JSON.stringify(Object.entries(unpacked).sort()) !== JSON.stringify(Object.entries(iso).sort())
  ) {
    throw new Error('the packed ISO table does not decode to the ISO table');
  }
  const codes = Object.keys(iso);
  out['iso4217.ts'] =
    header('data/iso4217-list-one.xml') +
    `\n/** Publication date of the ISO 4217 List One snapshot the table was generated from. */\n` +
    `export const ISO_4217_PUBLISHED = ${JSON.stringify(published)};\n\n` +
    `/** An active ISO 4217 code with a minor unit (${codes.length} codes). */\n` +
    `export type IsoCurrencyCode =\n${codes.map((code) => `  | ${JSON.stringify(code)}`).join('\n')};\n\n` +
    `/**\n * The ISO table, packed: 26 space-separated groups (A to Z), each listing the last two letters\n` +
    ` * of its codes, followed by the exponent when it is not 2.\n */\n` +
    `const PACKED = ${JSON.stringify(packed)};\n\n` +
    `/** ISO 4217 minor-unit exponent for every active code that has one. */\n` +
    `export const ISO_EXPONENTS: Readonly<Record<IsoCurrencyCode, number>> = /* @__PURE__ */ unpackIsoExponents(\n  PACKED,\n) as Record<IsoCurrencyCode, number>;\n\n` +
    UNPACK_SOURCE +
    `\n\n/** Active codes whose minor unit is "N.A." (precious metals, SDR, testing): not monetary, not in ISO_EXPONENTS. */\n` +
    `export const ISO_NON_MONETARY = ${JSON.stringify(nonMonetary)} as const;\n`;

  // Stripe: [exponent the API expects, multiple the charge amount must be, multiple a payout amount
  // must be]
  const stripeData = JSON.parse(read('data/stripe.json'));
  const stripe = {};
  for (const code of [...stripeData.presentment].sort()) {
    let entry = stripeData.defaultExponent;
    let charge = 1;
    let payout = 1;
    if (stripeData.zeroDecimal.includes(code)) {
      entry = 0;
    }
    if (stripeData.threeDecimal.includes(code)) {
      entry = 3;
      charge = 10;
      payout = 10;
    }
    const sc = stripeData.specialCases[code];
    if (sc) {
      entry = sc.apiExponent;
      if (code === 'ISK' || code === 'UGX') {
        charge = 100;
        payout = 100;
      }
      if (code === 'HUF' || code === 'TWD') {
        payout = 100;
      }
    }
    stripe[code] = [entry, charge, payout];
  }
  out['stripe.ts'] =
    header(
      'data/stripe.json (https://docs.stripe.com/currencies, retrieved ' +
        stripeData.retrieved +
        ')',
    ) +
    `\n/**\n * Stripe presentment currencies: [API exponent, charge amount multiple, payout amount multiple].\n` +
    ` * A multiple of 100 means "send a two-decimal value whose decimal part is always 00" (ISK, UGX)\n` +
    ` * or, for payouts only, whole units (HUF, TWD). A multiple of 10 is the three-decimal rule\n` +
    ` * (last digit must be 0).\n */\n` +
    `export const STRIPE_RULES: Readonly<Record<string, readonly [exponent: number, chargeMultiple: number, payoutMultiple: number]>> = ${obj(stripe)};\n`;

  const adyenData = JSON.parse(read('data/adyen.json'));
  const adyenRelative = isoRelativeExponents('Adyen', adyenData.exponents, iso);
  out['adyen.ts'] =
    header('data/adyen.json (' + adyenData.source + ', retrieved ' + adyenData.retrieved + ')') +
    (adyenRelative ? `import { ISO_EXPONENTS } from './iso4217.js';\n` : '') +
    `\n/** Adyen minor-unit exponents (Adyen's table is authoritative where it differs from ISO: CLP, CVE, IDR, ISK). */\n` +
    `export const ADYEN_EXPONENTS: Readonly<Record<string, number>> = ${adyenRelative ?? obj(adyenData.exponents) + ';\n'}`;

  // [API exponent, amount multiple, ...context multiples] when the data has multiples, else the
  // exponent
  for (const { file, name, extra = [], doc } of PROCESSORS) {
    const processorData = JSON.parse(read(`data/${file}.json`));
    const rules = {};
    for (const code of processorData.currencies.toSorted()) {
      let exponent = processorData.exponents?.[code] ?? processorData.defaultExponent;
      if (exponent === 'iso') {
        exponent = iso[code];
      }
      if (typeof exponent !== 'number') {
        throw new Error(`${file}: no exponent for ${code}`);
      }
      const multiple = processorData.multiples?.[code] ?? 1;
      rules[code] = processorData.multiples
        ? [exponent, multiple, ...extra.map((k) => processorData[k]?.[code] ?? multiple)]
        : exponent;
    }
    const tuple = [
      'exponent: number',
      'multiple: number',
      ...extra.map((k) => `${k.replace(/Multiples$/, '')}Multiple: number`),
    ];
    const type = processorData.multiples ? `readonly [${tuple.join(', ')}]` : 'number';
    const relative = processorData.multiples ? null : isoRelativeExponents(name, rules, iso);
    out[`${file}.ts`] =
      header(
        `data/${file}.json (${Object.values(processorData.sources)[0].url}, retrieved ${processorData.retrieved})`,
      ) +
      (relative ? `import { ISO_EXPONENTS } from './iso4217.js';\n` : '') +
      `\n/** ${doc} */\n` +
      `export const ${name}: Readonly<Record<string, ${type}>> = ${relative ?? obj(rules) + ';\n'}`;
  }

  const cashData = JSON.parse(read('data/cash-rounding.json'));
  const rules = cashData.rules.map((rule) => {
    const exp = iso[rule.currency];
    const [whole, fraction = ''] = rule.increment.split('.');
    if (fraction.length > exp) {
      throw new Error(`cash increment ${rule.increment} finer than ${rule.currency} exponent`);
    }
    const minor = Number(whole + fraction.padEnd(exp, '0'));
    return {
      currency: rule.currency,
      increment: minor,
      countries: rule.countries,
      scope: rule.scope,
      verified: rule.verified,
      source: rule.source,
    };
  });
  out['cash.ts'] =
    header('data/cash-rounding.json') +
    `\nexport interface CashRule {\n  readonly currency: string;\n  /** Smallest cash step, in ISO minor units. */\n  readonly increment: number;\n  readonly countries: readonly string[];\n  readonly scope: string;\n  /** false: only secondary sources were found. */\n  readonly verified: boolean;\n  readonly source: string;\n}\n\n` +
    `export const CASH_RULES: readonly CashRule[] = ${JSON.stringify(rules, null, 2)};\n`;
  return { out, entries, published };
}

const { out, entries, published } = generate();
const dir = join(root, 'src/generated');
let stale = false;
for (const [name, text] of Object.entries(out)) {
  const path = join(dir, name);
  let cur = null;
  try {
    cur = readFileSync(path, 'utf8');
  } catch {}
  if (cur !== text) {
    stale = true;
    if (!args.has('--check')) {
      mkdirSync(dir, { recursive: true });
      writeFileSync(path, text);
      console.log('wrote', path);
    }
  }
}
if (args.has('--check')) {
  if (stale) {
    console.error('src/generated is stale: run node scripts/gen-currencies.mjs');
    process.exit(1);
  }
  console.log('src/generated is up to date (ISO 4217 published ' + published + ')');
}
if (args.has('--fetch')) {
  const live = parseIsoXml(await (await fetch(SIX_URL)).text());
  const diffs = [];
  for (const [code, liveEntry] of live.entries) {
    const old = entries.get(code);
    if (!old) {
      diffs.push(`+ ${code} (exponent ${liveEntry.exponent}) added`);
    } else if (old.exponent !== liveEntry.exponent) {
      diffs.push(`~ ${code} exponent ${old.exponent} -> ${liveEntry.exponent}`);
    }
  }
  for (const code of entries.keys()) {
    if (!live.entries.has(code)) {
      diffs.push(`- ${code} withdrawn`);
    }
  }
  console.log(`live ISO 4217 list published ${live.published}; snapshot ${published}`);
  console.log(diffs.length ? diffs.join('\n') : 'no differences');
  if (diffs.length) {
    process.exitCode = 2;
  }
}
