#!/usr/bin/env node
// Writes ducat's adyenRate with an account time zone as cases for ducat's Rust `tz` feature
// (rust/crates/ducat/tests/it/adyen_tz.rs): for each zone, Creation Dates at midday in winter and
// summer, in a few other years, and around each of its clock changes in 2026 (the minute before a
// change, inside the gap or fold, and its last minute), each with the asOf the built TS gives. Run
// after `pnpm build`, on the reference runtime (Node 24, ICU 78.3):
//
//   node scripts/adyen-tz-cases.mjs > rust/crates/ducat/tests/it/adyen_tz_cases.rs
//   node scripts/adyen-tz-cases.mjs --all --tsv > /tmp/adyen-tz.tsv     (every zone Intl lists)
//   DUCAT_ADYEN_TZ_CASES=/tmp/adyen-tz.tsv \
//     cargo test -p ducat --features tz --test it adyen_tz:: -- --ignored
//
// Lines are written as they are computed (nothing is collected).
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const args = new Set(process.argv.slice(2));
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const { adyenRate } = await import(pathToFileURL(path.join(root, 'dist', 'adyen-fx.js')).href);

// Zones with something to test: summer time on either hemisphere, negative and two-hour summer
// time, half-hour and 45-minute offsets, changes at midnight, the date line, aliases and case.
const ZONES = [
  'UTC',
  'Europe/Amsterdam',
  'Europe/London',
  'Europe/Dublin',
  'Europe/Lisbon',
  'Europe/Moscow',
  'Africa/Casablanca',
  'Africa/Cairo',
  'America/New_York',
  'America/Chicago',
  'America/Phoenix',
  'America/Los_Angeles',
  'America/St_Johns',
  'America/Havana',
  'America/Santiago',
  'America/Asuncion',
  'America/Sao_Paulo',
  'America/Mexico_City',
  'Asia/Kolkata',
  'Asia/Kathmandu',
  'Asia/Tehran',
  'Asia/Jerusalem',
  'Asia/Beirut',
  'Asia/Tokyo',
  'Australia/Sydney',
  'Australia/Adelaide',
  'Australia/Lord_Howe',
  'Pacific/Auckland',
  'Pacific/Chatham',
  'Pacific/Apia',
  'Pacific/Kiritimati',
  'Antarctica/Troll',
  'Etc/GMT+12',
  'US/Pacific',
  'Asia/Calcutta',
  'EST5EDT',
  'europe/PARIS',
];

const zones = args.has('--all') ? Intl.supportedValuesOf('timeZone') : ZONES;
const tsv = args.has('--tsv');

const MINUTE = 60_000;
const HOUR = 60 * MINUTE;

const formatter = (timeZone) =>
  new Intl.DateTimeFormat('en-US', {
    timeZone,
    hourCycle: 'h23',
    year: 'numeric',
    month: 'numeric',
    day: 'numeric',
    hour: 'numeric',
    minute: 'numeric',
    second: 'numeric',
  });

/** The zone's offset at an instant, in milliseconds. */
function offsetAt(format, ms) {
  const parts = format.formatToParts(new Date(ms));
  const field = (type) => Number(parts.find((part) => part.type === type).value);
  const wall = Date.UTC(
    field('year'),
    field('month') - 1,
    field('day'),
    field('hour'),
    field('minute'),
    field('second'),
  );
  return wall - Math.floor(ms / 1000) * 1000;
}

/** The wall time of a UTC-like millisecond count, as Adyen writes Creation Date. */
const wall = (ms) => new Date(ms).toISOString().slice(0, 19).replace('T', ' ');

/** The zone's clock changes in a year: [instant, offset before, offset after]. */
function* changes(format, year) {
  let at = Date.UTC(year, 0, 1);
  const end = Date.UTC(year + 1, 0, 1);
  let offset = offsetAt(format, at);
  for (; at < end; at += HOUR) {
    const next = offsetAt(format, at + HOUR);
    if (next !== offset) {
      // to the minute: changes are on whole minutes
      let low = at;
      let high = at + HOUR;
      while (high - low > MINUTE) {
        const mid = low + Math.floor((high - low) / MINUTE / 2) * MINUTE;
        if (offsetAt(format, mid) === offset) {
          low = mid;
        } else {
          high = mid;
        }
      }
      yield [high, offset, next];
      offset = next;
    }
  }
}

/** Creation Dates for a zone, each once. */
function* creationDates(timeZone) {
  for (const year of [1975, 2000, 2026, 2040]) {
    yield `${year}-01-15 12:00:00`;
    yield `${year}-07-15 12:00:00`;
  }
  const format = formatter(timeZone);
  for (const [at, before, after] of changes(format, 2026)) {
    const early = at + Math.min(before, after);
    const late = at + Math.max(before, after);
    // the minute before the gap or fold, its first minute, its middle, its last minute
    yield wall(early - MINUTE);
    yield wall(early);
    yield wall(early + Math.floor((late - early) / MINUTE / 2) * MINUTE);
    yield wall(late - MINUTE);
    yield wall(late);
  }
}

const asOf = (created, timeZone) =>
  adyenRate(
    {
      'Gross Currency': 'USD',
      'Net Currency': 'EUR',
      'Exchange Rate': '0.9',
      'Creation Date': created,
    },
    { timeZone },
  )?.asOf;

const out = (line) => process.stdout.write(`${line}\n`);
if (!tsv) {
  out('// GENERATED by scripts/adyen-tz-cases.mjs from the built TS (dist/adyen-fx.js) on');
  out(
    `// Node ${process.version}, ICU ${process.versions.icu}, tzdb ${process.versions.tz}: do not edit.`,
  );
  out('');
  out("/// (account zone, Creation Date, ducat's asOf)");
  out('#[rustfmt::skip]');
  out('pub(crate) const CASES: &[(&str, &str, &str)] = &[');
}
for (const timeZone of zones) {
  const seen = new Set();
  for (const created of creationDates(timeZone)) {
    if (seen.has(created)) {
      continue;
    }
    seen.add(created);
    const expected = asOf(created, timeZone);
    if (tsv) {
      out(`${timeZone}\t${created}\t${expected}`);
    } else {
      out(
        `    (${JSON.stringify(timeZone)}, ${JSON.stringify(created)}, ${JSON.stringify(expected)}),`,
      );
    }
  }
}
if (!tsv) {
  out('];');
}
