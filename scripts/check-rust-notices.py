#!/usr/bin/env python3
"""Checks each Rust crate's NOTICE against the data the crate embeds.

A crate embeds third-party data through its generated source files, whose first lines say
`// GENERATED by <generator> from <inputs>.`, and through the few hand-copied tables marked
`// DATA from <source>`. Each input maps to the NOTICE sections (`[Section]` lines) it needs.
A crate's NOTICE must have exactly the sections its inputs need: none missing, none for data the
crate doesn't embed. An input this script doesn't know is an error, so a new data source can't
go into a crate without a NOTICE section. It also checks the licence that follows: a crate with
Unicode data is `MIT AND Unicode-3.0` and packages LICENSE-UNICODE; the others are MIT.

    python3 scripts/check-rust-notices.py        (from the repository root; CI runs it)
"""

import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CRATES = ROOT / "rust" / "crates"

# what a generated file names as its input -> the NOTICE sections that input needs
INPUTS = {
    "data/iso4217-list-one.xml": ["ISO 4217 List One"],
    "data/iso4217-list-three.xml": ["ISO 4217 List Three"],
    "data/historic.json": ["ISO 4217 List Three", "OpenJDK currency data"],
    "data/cldr-territories.json": ["Unicode CLDR 49: currency data"],
    "data/cldr-cash.json": ["Unicode CLDR 49: currency data"],
    "data/cash-rounding.json": ["Cash-rounding rules"],
    "data/crypto-units.json": ["Crypto units"],
    "data/stripe.json": ["Stripe documentation"],
    "data/adyen.json": ["Adyen documentation"],
    "data/checkout.json": ["Checkout.com documentation"],
    "data/paypal.json": ["PayPal documentation"],
    "data/braintree.json": ["Braintree documentation"],
    "data/klarna.json": ["Klarna documentation"],
    "data/rbnf/*.txt": ["Unicode CLDR 49: spell-out rules (RBNF)"],
    "data/icu/": ["ICU 78.3 overrides"],
    # data/cldr/ is CLDR 48: which files a crate reads differs, so each crate has its own section
    ("ducat-words", "data/cldr/"): ["Unicode CLDR 48: plurals, numbers and list patterns"],
    ("ducat-format", "data/cldr/"): ["Unicode CLDR 48: locale data"],
    "the Unicode Character Database (Unicode 17.0)": ["Unicode Character Database 17.0"],
}

# the sections whose data is under the Unicode License v3
UNICODE = {
    "Unicode CLDR 49: currency data",
    "Unicode CLDR 49: spell-out rules (RBNF)",
    "Unicode CLDR 48: plurals, numbers and list patterns",
    "Unicode CLDR 48: locale data",
    "ICU 78.3 overrides",
    "Unicode Character Database 17.0",
}

WORKSPACE = tomllib.loads((ROOT / "rust" / "Cargo.toml").read_text(encoding="utf-8"))

HEADER = re.compile(r"^// (?:GENERATED by \S+|DATA) from (.*)$")


def inputs(path):
    """The inputs a source file's header names, or [] for a file that embeds no data."""
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or not (match := HEADER.match(lines[0])):
        return []
    # the header runs on over further `//` lines until the regeneration instruction
    text = match.group(1)
    for line in lines[1:]:
        if not line.startswith("// ") or line.startswith("// Do not edit"):
            break
        text += " " + line[3:]
    text = text.rstrip(".")
    if text.startswith("data/: "):
        # `data/: a.json, b.json and c.xml`
        names = re.split(r", | and ", text[len("data/: ") :])
        return ["data/" + name for name in names]
    found = re.findall(r"data/\S*", text)
    return [name.rstrip(".,") for name in found] or [text]


def check(crate):
    errors = []
    required = {}
    for path in sorted((crate / "src").rglob("*.rs")):
        for name in inputs(path):
            key = (crate.name, name) if (crate.name, name) in INPUTS else name
            if key not in INPUTS:
                errors.append(f"{path.relative_to(ROOT)}: unknown input {name!r}: add it to INPUTS")
                continue
            for section in INPUTS[key]:
                required.setdefault(section, path.relative_to(ROOT))
    notice_path = crate / "NOTICE"
    if notice_path.is_symlink() or not notice_path.is_file():
        return errors + [f"{notice_path.relative_to(ROOT)}: must be the crate's own file"]
    notice = notice_path.read_text(encoding="utf-8")
    sections = re.findall(r"^\[(.+)\]$", notice, re.MULTILINE)
    for section in required:
        if section not in sections:
            errors.append(f"{crate.name}/NOTICE: no [{section}] section ({required[section]} embeds it)")
    for section in sections:
        if section not in required:
            errors.append(f"{crate.name}/NOTICE: [{section}], which no file of the crate embeds")
    if not sections and "embeds no third-party data" not in notice:
        errors.append(f"{crate.name}/NOTICE: no sections, and doesn't say it embeds no data")

    package = tomllib.loads((crate / "Cargo.toml").read_text(encoding="utf-8"))["package"]
    license = package.get("license", {"workspace": True})
    if license == {"workspace": True}:
        license = WORKSPACE["workspace"]["package"]["license"]
    include = package.get("include", [])
    if "/NOTICE" not in include:
        errors.append(f"{crate.name}/Cargo.toml: NOTICE is not in include")
    if UNICODE & required.keys():
        if license != "MIT AND Unicode-3.0":
            errors.append(f"{crate.name}/Cargo.toml: embeds Unicode data, so license = \"MIT AND Unicode-3.0\"")
        if not (crate / "LICENSE-UNICODE").is_file() or "/LICENSE-UNICODE" not in include:
            errors.append(f"{crate.name}: embeds Unicode data, so it packages LICENSE-UNICODE")
    else:
        if license != "MIT":
            errors.append(f"{crate.name}/Cargo.toml: embeds no Unicode data, so its licence is MIT")
        if (crate / "LICENSE-UNICODE").exists() or "/LICENSE-UNICODE" in include:
            errors.append(f"{crate.name}: embeds no Unicode data, so it has no LICENSE-UNICODE")
    return errors


def main():
    errors = []
    crates = sorted(path.parent for path in CRATES.glob("*/Cargo.toml"))
    for crate in crates:
        errors += check(crate)
    for error in errors:
        print(error, file=sys.stderr)
    if errors:
        return 1
    print(f"NOTICE and licence match the embedded data in {len(crates)} crates")
    return 0


if __name__ == "__main__":
    sys.exit(main())
