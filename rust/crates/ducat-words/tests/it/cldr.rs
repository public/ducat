//! The generators of `src/cldr.rs` (each language's plural rules, digit grouping and word for
//! "and") and `src/names.rs` (each language's currency names, feature `cldr-names`), from the
//! repository's CLDR 48 snapshot in `data/cldr/`, and the checks that the committed files are their
//! output. To regenerate them:
//!
//! ```text
//! DUCAT_REGENERATE=1 cargo test -p ducat-words --test it cldr::
//! ```

use std::fmt::Write as _;

use serde_json::Value;

use crate::common::{LANGUAGES, root};

/// The plural categories in CLDR's order; "other" is what no rule matches.
const CATEGORIES: [&str; 5] = ["zero", "one", "two", "few", "many"];

/// `plural::operand` keeps a whole number's last six digits (and whether it is a million or
/// more), which decides every relation whose modulus divides a million and whose values are
/// below one: the generator refuses any other.
const MILLION: u64 = 1_000_000;

fn json(relative: &str) -> Value {
    let path = root().join("data/cldr").join(relative);
    serde_json::from_str(&std::fs::read_to_string(&path).unwrap()).unwrap()
}

/// One relation, `n % 100 != 11..13`, as the Rust expression `src/cldr.rs` holds.
fn relation(text: &str) -> String {
    let (left, operator, right) = if let Some((left, right)) = text.split_once("!=") {
        (left, false, right)
    } else {
        let (left, right) = text.split_once('=').unwrap();
        (left, true, right)
    };
    let (operand, modulus) = match left.trim().split_once('%') {
        Some((operand, modulus)) => (operand.trim(), modulus.trim().parse::<u64>().unwrap()),
        None => (left.trim(), 0),
    };
    assert!(
        modulus == 0 || MILLION % modulus == 0,
        "modulus {modulus} in {text:?}"
    );
    let operand = match operand {
        "n" | "i" => "Whole",
        // the fraction and exponent operands are zero for a whole number
        "v" | "w" | "f" | "t" | "c" | "e" => "Zero",
        other => panic!("plural operand {other} in {text:?}"),
    };
    let mut ranges = Vec::new();
    for item in right.split(',') {
        let (low, high) = item
            .trim()
            .split_once("..")
            .unwrap_or((item.trim(), item.trim()));
        let (low, high) = (low.parse::<u64>().unwrap(), high.parse::<u64>().unwrap());
        assert!(high < MILLION, "value {high} in {text:?}");
        ranges.push(format!("({low}, {high})"));
    }
    format!(
        "Relation {{ operand: Operand::{operand}, modulus: {modulus}, equal: {operator}, ranges: &[{}] }}",
        ranges.join(", ")
    )
}

/// A language's rules: each category's condition, `or` of `and` of relations.
fn rules(rules: &Value) -> String {
    let mut out = Vec::new();
    for category in CATEGORIES {
        let Some(rule) = rules.get(format!("pluralRule-count-{category}")) else {
            continue;
        };
        let condition = rule.as_str().unwrap().split('@').next().unwrap().trim();
        let alternatives = condition
            .split(" or ")
            .map(|alternative| {
                let all = alternative.split(" and ").map(relation).collect::<Vec<_>>();
                format!("&[{}]", all.join(", "))
            })
            .collect::<Vec<_>>();
        out.push(format!(
            "Rule {{ category: {category:?}, any: &[{}] }}",
            alternatives.join(", ")
        ));
    }
    format!("&[{}]", out.join(", "))
}

fn generate() -> String {
    let cardinal = json("supplemental/plurals.json");
    let ordinal = json("supplemental/ordinals.json");
    let mut out = String::new();
    writeln!(
        out,
        "// GENERATED by rust/crates/ducat-words/tests/it/cldr.rs from data/cldr/ (CLDR 48)."
    )
    .unwrap();
    writeln!(
        out,
        "// Do not edit by hand: run `DUCAT_REGENERATE=1 cargo test -p ducat-words --test it cldr::`."
    )
    .unwrap();
    writeln!(out).unwrap();
    writeln!(out, "use crate::plural::{{Operand, Relation, Rule}};").unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "/// What a language takes from CLDR besides its RBNF rules."
    )
    .unwrap();
    writeln!(out, "pub(crate) struct LocaleData {{").unwrap();
    writeln!(
        out,
        "    /// The decimal format's group separator (`symbols-numberSystem-latn`)."
    )
    .unwrap();
    writeln!(out, "    pub(crate) group: &'static str,").unwrap();
    writeln!(
        out,
        "    /// The fewest digits before the first group for grouping to apply."
    )
    .unwrap();
    writeln!(out, "    pub(crate) minimum_grouping: usize,").unwrap();
    writeln!(
        out,
        "    /// \"and\" between two items, with its spaces (the standard list pattern for two)."
    )
    .unwrap();
    writeln!(out, "    pub(crate) conjunction: &'static str,").unwrap();
    writeln!(
        out,
        "    /// The cardinal plural rules, in CLDR's category order."
    )
    .unwrap();
    writeln!(out, "    pub(crate) cardinal: &'static [Rule],").unwrap();
    writeln!(out, "    /// The ordinal plural rules.").unwrap();
    writeln!(out, "    pub(crate) ordinal: &'static [Rule],").unwrap();
    writeln!(out, "}}").unwrap();
    for (language, name) in LANGUAGES {
        let numbers = json(&format!("main/{language}/numbers.json"));
        let numbers = &numbers["main"][language]["numbers"];
        assert_eq!(numbers["defaultNumberingSystem"], "latn", "{language}");
        let group = numbers["symbols-numberSystem-latn"]["group"]
            .as_str()
            .unwrap();
        let minimum: usize = numbers["minimumGroupingDigits"]
            .as_str()
            .unwrap()
            .parse()
            .unwrap();
        // the rules write digits as `#,##0`: three-digit groups, which this file assumes
        assert_eq!(
            numbers["decimalFormats-numberSystem-latn"]["standard"], "#,##0.###",
            "{language}"
        );
        let lists = json(&format!("main/{language}/listPatterns.json"));
        let pair = lists["main"][language]["listPatterns"]["listPattern-type-standard"]["2"]
            .as_str()
            .unwrap();
        let conjunction = pair
            .strip_prefix("{0}")
            .and_then(|rest| rest.strip_suffix("{1}"))
            .unwrap();
        writeln!(out).unwrap();
        writeln!(out, "/// `{language}`.").unwrap();
        writeln!(out, "pub(crate) const {name}: LocaleData = LocaleData {{").unwrap();
        writeln!(out, "    group: {group:?},").unwrap();
        writeln!(out, "    minimum_grouping: {minimum},").unwrap();
        writeln!(out, "    conjunction: {conjunction:?},").unwrap();
        writeln!(
            out,
            "    cardinal: {},",
            rules(&cardinal["supplemental"]["plurals-type-cardinal"][language])
        )
        .unwrap();
        writeln!(
            out,
            "    ordinal: {},",
            rules(&ordinal["supplemental"]["plurals-type-ordinal"][language])
        )
        .unwrap();
        writeln!(out, "}};").unwrap();
    }
    out
}

/// The plural categories a currency name can have in `language`: its cardinal rules' categories
/// and `other`, which the generator checks are among the ones `UnitNames` holds.
fn name_categories(cardinal: &Value, language: &str) -> Vec<&'static str> {
    let rules = &cardinal["supplemental"]["plurals-type-cardinal"][language];
    let mut categories: Vec<&'static str> = CATEGORIES
        .into_iter()
        .filter(|category| rules.get(format!("pluralRule-count-{category}")).is_some())
        .collect();
    for category in &categories {
        assert!(
            ["one", "many"].contains(category),
            "{language} has plural category {category}, which src/names.rs doesn't hold"
        );
    }
    categories.push("other");
    categories
}

/// `src/names.rs`: each language's currency display names by plural category, as `Intl` writes
/// a whole number of the currency with `currencyDisplay: 'name'` (ICU takes a category's name,
/// else `other`'s, else the display name, else the code).
fn generate_names() -> String {
    let cardinal = json("supplemental/plurals.json");
    let root_currencies = json("main/und/currencies.json");
    for (code, fields) in root_currencies["main"]["und"]["numbers"]["currencies"]
        .as_object()
        .unwrap()
    {
        // the languages inherit from root: it must have no names to inherit
        assert!(
            fields
                .as_object()
                .unwrap()
                .keys()
                .all(|key| !key.starts_with("displayName")),
            "root names {code}"
        );
    }
    let mut out = String::new();
    writeln!(
        out,
        "// GENERATED by rust/crates/ducat-words/tests/it/cldr.rs from data/cldr/ (CLDR 48)."
    )
    .unwrap();
    writeln!(
        out,
        "// Do not edit by hand: run `DUCAT_REGENERATE=1 cargo test -p ducat-words --test it cldr::`."
    )
    .unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "/// A currency's display names in a language, by the plural categories its rules have."
    )
    .unwrap();
    writeln!(out, "pub(crate) struct CurrencyNames {{").unwrap();
    writeln!(out, "    /// The ISO 4217 code.").unwrap();
    writeln!(out, "    pub(crate) code: &'static str,").unwrap();
    writeln!(
        out,
        "    /// `displayName-count-other` (else `displayName`)."
    )
    .unwrap();
    writeln!(out, "    pub(crate) other: &'static str,").unwrap();
    writeln!(
        out,
        "    /// `displayName-count-one`, where CLDR has one that isn't `other`'s."
    )
    .unwrap();
    writeln!(out, "    pub(crate) one: Option<&'static str>,").unwrap();
    writeln!(
        out,
        "    /// `displayName-count-many`, where CLDR has one that isn't `other`'s."
    )
    .unwrap();
    writeln!(out, "    pub(crate) many: Option<&'static str>,").unwrap();
    writeln!(out, "}}").unwrap();
    for (language, name) in LANGUAGES {
        let categories = name_categories(&cardinal, language);
        let numbers = json(&format!("main/{language}/numbers.json"));
        let formats = numbers["main"][language]["numbers"]["currencyFormats-numberSystem-latn"]
            .as_object()
            .unwrap();
        // the crate writes a name after the number and a plain space
        for (key, pattern) in formats {
            if key.starts_with("unitPattern-count-") {
                assert_eq!(pattern, "{0} {1}", "{language} {key}");
            }
        }
        let currencies = json(&format!("main/{language}/currencies.json"));
        let locale = &currencies["main"][language];
        assert_eq!(locale["inherits"], "und", "{language}");
        let mut codes: Vec<_> = locale["numbers"]["currencies"]
            .as_object()
            .unwrap()
            .iter()
            .collect();
        codes.sort_by(|left, right| left.0.cmp(right.0));
        writeln!(out).unwrap();
        writeln!(out, "/// `{language}`.").unwrap();
        writeln!(out, "#[cfg(feature = {language:?})]").unwrap();
        writeln!(out, "pub(crate) const {name}: &[CurrencyNames] = &[").unwrap();
        for (code, fields) in codes {
            assert!(
                code.len() == 3 && code.bytes().all(|byte| byte.is_ascii_uppercase()),
                "{language} {code}"
            );
            let field = |key: &str| fields.get(key).map(|value| value.as_str().unwrap());
            let Some(display) = field("displayName") else {
                // symbols only: Intl writes the code
                assert!(
                    fields
                        .as_object()
                        .unwrap()
                        .keys()
                        .all(|key| !key.starts_with("displayName")),
                    "{language} {code}"
                );
                continue;
            };
            let other = field("displayName-count-other").unwrap_or(display);
            let form = |category: &str| {
                if !categories.contains(&category) {
                    return "None".to_owned();
                }
                match field(&format!("displayName-count-{category}")) {
                    Some(text) if text != other => format!("Some({text:?})"),
                    _ => "None".to_owned(),
                }
            };
            writeln!(
                out,
                "    CurrencyNames {{ code: {code:?}, other: {other:?}, one: {}, many: {} }},",
                form("one"),
                form("many")
            )
            .unwrap();
        }
        writeln!(out, "];").unwrap();
    }
    out
}

#[test]
fn committed_names_are_the_generators_output() {
    let path = root().join("rust/crates/ducat-words/src/names.rs");
    let generated = generate_names();
    if std::env::var_os("DUCAT_REGENERATE").is_some() {
        std::fs::write(&path, &generated).unwrap();
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == generated,
        "src/names.rs is stale: run `DUCAT_REGENERATE=1 cargo test -p ducat-words --test it cldr::`"
    );
}

#[test]
fn committed_cldr_data_is_the_generators_output() {
    let path = root().join("rust/crates/ducat-words/src/cldr.rs");
    let generated = generate();
    if std::env::var_os("DUCAT_REGENERATE").is_some() {
        std::fs::write(&path, &generated).unwrap();
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == generated,
        "src/cldr.rs is stale: run `DUCAT_REGENERATE=1 cargo test -p ducat-words --test it cldr::`"
    );
}
