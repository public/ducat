//! The generator of `src/rules.rs` (CLDR's RBNF rule text for each language, from the repository's
//! `data/rbnf/*.txt`), and the check that the committed file is its output. To regenerate it:
//!
//! ```text
//! DUCAT_REGENERATE=1 cargo test -p ducat-words --test rules
//! ```

use std::fmt::Write as _;
use std::path::PathBuf;

const LANGUAGES: [(&str, &str); 7] = [
    ("en", "EN"),
    ("de", "DE"),
    ("fr", "FR"),
    ("es", "ES"),
    ("it", "IT"),
    ("nl", "NL"),
    ("pt", "PT"),
];

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../..")
}

fn generate() -> String {
    let mut out = String::new();
    writeln!(
        out,
        "// GENERATED by rust/crates/ducat-words/tests/rules.rs from data/rbnf/*.txt (CLDR 49)."
    )
    .unwrap();
    writeln!(
        out,
        "// Do not edit by hand: run `DUCAT_REGENERATE=1 cargo test -p ducat-words --test rules`."
    )
    .unwrap();
    for (file, name) in LANGUAGES {
        let raw = std::fs::read_to_string(root().join(format!("data/rbnf/{file}.txt"))).unwrap();
        // the first line names the source; blank lines and comments are left out, as ducat's
        // generator (scripts/gen-currencies.mjs) leaves them out of its rule text
        let source = raw.lines().next().unwrap_or("").trim_start_matches("# ");
        let text = raw
            .split('\n')
            .filter(|line| !line.trim().is_empty() && !line.starts_with('#'))
            .collect::<Vec<_>>()
            .join("\n");
        writeln!(out).unwrap();
        writeln!(
            out,
            "/// CLDR's RBNF rules for `{file}` ({} bytes), from {source}.",
            text.len()
        )
        .unwrap();
        writeln!(out, "#[cfg(feature = \"{file}\")]").unwrap();
        writeln!(out, "pub(crate) const {name}: &str = {text:?};").unwrap();
    }
    out
}

#[test]
fn committed_rules_are_the_generators_output() {
    let path = root().join("rust/crates/ducat-words/src/rules.rs");
    let generated = generate();
    if std::env::var_os("DUCAT_REGENERATE").is_some() {
        std::fs::write(&path, &generated).unwrap();
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == generated,
        "src/rules.rs is stale: run `DUCAT_REGENERATE=1 cargo test -p ducat-words --test rules`"
    );
}
