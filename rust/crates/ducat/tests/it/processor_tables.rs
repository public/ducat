//! The generator of `src/processors/tables.rs`, and the check that the committed file is its
//! output.
//!
//! The tables come from the repository's `data/`: `stripe.json`, `adyen.json`, `checkout.json`,
//! `paypal.json`, `braintree.json` and `klarna.json`, with ISO 4217 List One
//! (`iso4217-list-one.xml`) for the processors whose exponents default to ISO's. To regenerate it:
//!
//! ```text
//! DUCAT_REGENERATE=1 cargo test -p ducat --test it processor_tables::
//! ```

use std::collections::BTreeMap;
use std::fmt::Write as _;

use serde_json::Value;

use crate::common::root;

fn json(name: &str) -> Value {
    serde_json::from_str(&std::fs::read_to_string(root().join("data").join(name)).unwrap()).unwrap()
}

/// The text of the first `<tag>…</tag>` inside `entry`.
fn element<'a>(entry: &'a str, tag: &str) -> Option<&'a str> {
    let open = entry.find(&format!("<{tag}>"))?;
    let start = open + tag.len() + 2;
    let end = start + entry[start..].find(&format!("</{tag}>"))?;
    Some(entry[start..end].trim())
}

/// ISO 4217 List One: code → exponent, for the codes with a minor unit.
fn iso() -> BTreeMap<String, u64> {
    let xml = std::fs::read_to_string(root().join("data/iso4217-list-one.xml")).unwrap();
    xml.split("<CcyNtry>")
        .skip(1)
        .filter_map(|entry| {
            let code = element(entry, "Ccy")?;
            let units = element(entry, "CcyMnrUnts")?.parse().ok()?;
            Some((code.to_owned(), units))
        })
        .collect()
}

fn codes(value: &Value) -> Vec<String> {
    value
        .as_array()
        .unwrap()
        .iter()
        .map(|code| code.as_str().unwrap().to_owned())
        .collect()
}

fn number(value: &Value) -> u64 {
    value.as_u64().unwrap()
}

/// Stripe: two decimals unless listed as zero- or three-decimal (a multiple of 10), or a special
/// case with its own API exponent. ISK and UGX are two-decimal values ending in 00 (a multiple of
/// 100); HUF and TWD payouts are whole units (a payout multiple of 100). Code → (exponent, charge
/// multiple, payout multiple).
fn stripe() -> BTreeMap<String, (u64, u64, u64)> {
    let data = json("stripe.json");
    let (zero, three) = (codes(&data["zeroDecimal"]), codes(&data["threeDecimal"]));
    codes(&data["presentment"])
        .into_iter()
        .map(|code| {
            let (mut exponent, mut charge, mut payout) = (number(&data["defaultExponent"]), 1, 1);
            if zero.contains(&code) {
                exponent = 0;
            }
            if three.contains(&code) {
                (exponent, charge, payout) = (3, 10, 10);
            }
            if let Some(special) = data["specialCases"].get(&code) {
                exponent = number(&special["apiExponent"]);
                if code == "ISK" || code == "UGX" {
                    (charge, payout) = (100, 100);
                }
                if code == "HUF" || code == "TWD" {
                    payout = 100;
                }
            }
            (code, (exponent, charge, payout))
        })
        .collect()
}

/// Checkout.com: its listed exponents, the default for the others; the payment multiple and the
/// Standalone API's. Code → (exponent, multiple, standalone multiple).
fn checkout() -> BTreeMap<String, (u64, u64, u64)> {
    let data = json("checkout.json");
    codes(&data["currencies"])
        .into_iter()
        .map(|code| {
            let exponent = data["exponents"]
                .get(&code)
                .map_or(number(&data["defaultExponent"]), number);
            let multiple = data["multiples"].get(&code).map_or(1, number);
            let standalone = data["standaloneMultiples"]
                .get(&code)
                .map_or(multiple, number);
            (code, (exponent, multiple, standalone))
        })
        .collect()
}

/// PayPal, Braintree and Klarna: the listed exponents, ISO's for the others.
fn iso_default(name: &str, iso: &BTreeMap<String, u64>) -> BTreeMap<String, u64> {
    let data = json(name);
    assert_eq!(data["defaultExponent"], "iso");
    codes(&data["currencies"])
        .into_iter()
        .map(|code| {
            let exponent = data
                .get("exponents")
                .and_then(|exponents| exponents.get(&code))
                .map(number)
                .unwrap_or_else(|| {
                    *iso.get(&code)
                        .unwrap_or_else(|| panic!("{name}: no exponent for {code}"))
                });
            (code, exponent)
        })
        .collect()
}

fn generate() -> String {
    let iso = iso();
    let mut out = String::new();
    let mut line = |text: &str| writeln!(out, "{text}").unwrap();
    line(
        "// GENERATED by rust/crates/ducat/tests/it/processor_tables.rs from data/: stripe.json, adyen.json,",
    );
    line("// checkout.json, paypal.json, braintree.json, klarna.json and iso4217-list-one.xml.");
    line(
        "// Do not edit by hand: run `DUCAT_REGENERATE=1 cargo test -p ducat --test it processor_tables::`.",
    );
    line("");
    let triples = |line: &mut dyn FnMut(&str),
                   feature: &str,
                   name: &str,
                   doc: &str,
                   table: &BTreeMap<String, (u64, u64, u64)>| {
        line(&format!("/// {doc} ({} codes, sorted).", table.len()));
        line(&format!("#[cfg(feature = \"{feature}\")]"));
        line(&format!(
            "pub(crate) const {name}: [(&str, u8, u64, u64); {}] = [",
            table.len()
        ));
        for (code, (exponent, first, second)) in table {
            line(&format!("    ({code:?}, {exponent}, {first}, {second}),"));
        }
        line("];");
        line("");
    };
    triples(
        &mut line,
        "stripe",
        "STRIPE",
        "Stripe presentment currencies: code, API exponent, charge multiple, payout multiple",
        &stripe(),
    );
    triples(
        &mut line,
        "checkout",
        "CHECKOUT",
        "Checkout.com currencies: code, API exponent, payment multiple, Standalone API multiple",
        &checkout(),
    );
    let adyen = json("adyen.json");
    let adyen: BTreeMap<String, u64> = adyen["exponents"]
        .as_object()
        .unwrap()
        .iter()
        .map(|(code, exponent)| (code.clone(), number(exponent)))
        .collect();
    let mut singles = |feature: &str, name: &str, doc: &str, table: &BTreeMap<String, u64>| {
        line(&format!("/// {doc} ({} codes, sorted).", table.len()));
        line(&format!("#[cfg(feature = \"{feature}\")]"));
        line(&format!(
            "pub(crate) const {name}: [(&str, u8); {}] = [",
            table.len()
        ));
        for (code, exponent) in table {
            line(&format!("    ({code:?}, {exponent}),"));
        }
        line("];");
        line("");
    };
    singles(
        "adyen",
        "ADYEN",
        "Adyen's minor-unit exponents: code, exponent",
        &adyen,
    );
    singles(
        "paypal",
        "PAYPAL",
        "PayPal's decimals per currency: code, decimals",
        &iso_default("paypal.json", &iso),
    );
    singles(
        "braintree",
        "BRAINTREE",
        "Braintree's decimals per currency: code, decimals",
        &iso_default("braintree.json", &iso),
    );
    singles(
        "klarna",
        "KLARNA",
        "Klarna's purchase currencies and their ISO 4217 exponents",
        &iso_default("klarna.json", &iso),
    );
    out.pop();
    out
}

#[test]
fn committed_tables_are_the_generators_output() {
    let path = root().join("rust/crates/ducat/src/processors/tables.rs");
    let generated = generate();
    if std::env::var_os("DUCAT_REGENERATE").is_some() {
        std::fs::write(&path, &generated).unwrap();
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == generated,
        "src/processors/tables.rs is stale: run `DUCAT_REGENERATE=1 cargo test -p ducat --test it processor_tables::`"
    );
}
