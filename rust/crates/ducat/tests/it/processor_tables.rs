//! The generator of `src/processors/tables.rs`, and the check that the committed file is its
//! output.
//!
//! The tables come from the repository's `data/`: `stripe.json`, `adyen.json`, `checkout.json`,
//! `paypal.json`, `braintree.json` and `klarna.json`, with ISO 4217 List One
//! (`iso4217-list-one.xml`) for the processors whose exponents default to ISO's. To regenerate it:
//!
//! ```text
//! DUCAT_REGENERATE=1 cargo test -p ducat --test it processor_tables::
//! ```

use std::collections::BTreeMap;
use std::fmt::Write as _;

use serde_json::Value;

use crate::common::root;

fn json(name: &str) -> Value {
    serde_json::from_str(&std::fs::read_to_string(root().join("data").join(name)).unwrap()).unwrap()
}

/// The text of the first `<tag>…</tag>` inside `entry`.
fn element<'a>(entry: &'a str, tag: &str) -> Option<&'a str> {
    let open = entry.find(&format!("<{tag}>"))?;
    let start = open + tag.len() + 2;
    let end = start + entry[start..].find(&format!("</{tag}>"))?;
    Some(entry[start..end].trim())
}

/// ISO 4217 List One: code → exponent, for the codes with a minor unit.
fn iso() -> BTreeMap<String, u64> {
    let xml = std::fs::read_to_string(root().join("data/iso4217-list-one.xml")).unwrap();
    xml.split("<CcyNtry>")
        .skip(1)
        .filter_map(|entry| {
            let code = element(entry, "Ccy")?;
            let units = element(entry, "CcyMnrUnts")?.parse().ok()?;
            Some((code.to_owned(), units))
        })
        .collect()
}

fn codes(value: &Value) -> Vec<String> {
    value
        .as_array()
        .unwrap()
        .iter()
        .map(|code| code.as_str().unwrap().to_owned())
        .collect()
}

fn number(value: &Value) -> u64 {
    value.as_u64().unwrap()
}

/// Stripe: two decimals unless listed as zero- or three-decimal (a multiple of 10), or a special
/// case with its own API exponent. ISK and UGX are two-decimal values ending in 00 (a multiple of
/// 100); HUF and TWD payouts are whole units (a payout multiple of 100). Code → (exponent, charge
/// multiple, payout multiple).
fn stripe() -> BTreeMap<String, (u64, u64, u64)> {
    let data = json("stripe.json");
    let (zero, three) = (codes(&data["zeroDecimal"]), codes(&data["threeDecimal"]));
    codes(&data["presentment"])
        .into_iter()
        .map(|code| {
            let (mut exponent, mut charge, mut payout) = (number(&data["defaultExponent"]), 1, 1);
            if zero.contains(&code) {
                exponent = 0;
            }
            if three.contains(&code) {
                (exponent, charge, payout) = (3, 10, 10);
            }
            if let Some(special) = data["specialCases"].get(&code) {
                exponent = number(&special["apiExponent"]);
                if code == "ISK" || code == "UGX" {
                    (charge, payout) = (100, 100);
                }
                if code == "HUF" || code == "TWD" {
                    payout = 100;
                }
            }
            (code, (exponent, charge, payout))
        })
        .collect()
}

/// Checkout.com: its listed exponents, the default for the others; the payment multiple and the
/// Standalone API's. Code → (exponent, multiple, standalone multiple).
fn checkout() -> BTreeMap<String, (u64, u64, u64)> {
    let data = json("checkout.json");
    codes(&data["currencies"])
        .into_iter()
        .map(|code| {
            let exponent = data["exponents"]
                .get(&code)
                .map_or(number(&data["defaultExponent"]), number);
            let multiple = data["multiples"].get(&code).map_or(1, number);
            let standalone = data["standaloneMultiples"]
                .get(&code)
                .map_or(multiple, number);
            (code, (exponent, multiple, standalone))
        })
        .collect()
}

/// PayPal, Braintree and Klarna: the listed exponents, ISO's for the others.
fn iso_default(name: &str, iso: &BTreeMap<String, u64>) -> BTreeMap<String, u64> {
    let data = json(name);
    assert_eq!(data["defaultExponent"], "iso");
    codes(&data["currencies"])
        .into_iter()
        .map(|code| {
            let exponent = data
                .get("exponents")
                .and_then(|exponents| exponents.get(&code))
                .map(number)
                .unwrap_or_else(|| {
                    *iso.get(&code)
                        .unwrap_or_else(|| panic!("{name}: no exponent for {code}"))
                });
            (code, exponent)
        })
        .collect()
}

fn generate() -> String {
    let iso = iso();
    let mut out = String::new();
    let mut line = |text: &str| writeln!(out, "{text}").unwrap();
    line(
        "// GENERATED by rust/crates/ducat/tests/it/processor_tables.rs from data/: stripe.json, adyen.json,",
    );
    line("// checkout.json, paypal.json, braintree.json, klarna.json and iso4217-list-one.xml.");
    line(
        "// Do not edit by hand: run `DUCAT_REGENERATE=1 cargo test -p ducat --test it processor_tables::`.",
    );
    line("");
    line(
        "#[cfg(any(feature = \"adyen\", feature = \"braintree\", feature = \"klarna\", feature = \"paypal\"))]",
    );
    line("use super::ExponentEntry;");
    line("#[cfg(feature = \"checkout\")]");
    line("use super::checkout::CheckoutEntry;");
    line("#[cfg(feature = \"stripe\")]");
    line("use super::stripe::StripeEntry;");
    line("");
    // (feature, table name, entry type, the names of the two multiples)
    type Triple<'a> = (&'a str, &'a str, &'a str, [&'a str; 2]);
    let triples = |line: &mut dyn FnMut(&str),
                   (feature, name, entry, [first_name, second_name]): Triple<'_>,
                   doc: &str,
                   table: &BTreeMap<String, (u64, u64, u64)>| {
        line(&format!("/// {doc} ({} codes, sorted).", table.len()));
        line(&format!("#[cfg(feature = \"{feature}\")]"));
        line(&format!(
            "pub(crate) static {name}: [{entry}; {}] = [",
            table.len()
        ));
        for (code, (exponent, first, second)) in table {
            line(&format!(
                "    {entry} {{ code: {code:?}, exponent: {exponent}, {first_name}: {first}, {second_name}: {second} }},"
            ));
        }
        line("];");
        line("");
    };
    triples(
        &mut line,
        (
            "stripe",
            "STRIPE",
            "StripeEntry",
            ["charge_multiple", "payout_multiple"],
        ),
        "Stripe presentment currencies: code, API exponent, charge multiple, payout multiple",
        &stripe(),
    );
    triples(
        &mut line,
        (
            "checkout",
            "CHECKOUT",
            "CheckoutEntry",
            ["multiple", "standalone_multiple"],
        ),
        "Checkout.com currencies: code, API exponent, payment multiple, Standalone API multiple",
        &checkout(),
    );
    let adyen = json("adyen.json");
    let adyen: BTreeMap<String, u64> = adyen["exponents"]
        .as_object()
        .unwrap()
        .iter()
        .map(|(code, exponent)| (code.clone(), number(exponent)))
        .collect();
    let mut singles = |feature: &str, name: &str, doc: &str, table: &BTreeMap<String, u64>| {
        line(&format!("/// {doc} ({} codes, sorted).", table.len()));
        line(&format!("#[cfg(feature = \"{feature}\")]"));
        line(&format!(
            "pub(crate) static {name}: [ExponentEntry; {}] = [",
            table.len()
        ));
        for (code, exponent) in table {
            line(&format!(
                "    ExponentEntry {{ code: {code:?}, exponent: {exponent} }},"
            ));
        }
        line("];");
        line("");
    };
    singles(
        "adyen",
        "ADYEN",
        "Adyen's minor-unit exponents: code, exponent",
        &adyen,
    );
    singles(
        "paypal",
        "PAYPAL",
        "PayPal's decimals per currency: code, decimals",
        &iso_default("paypal.json", &iso),
    );
    singles(
        "braintree",
        "BRAINTREE",
        "Braintree's decimals per currency: code, decimals",
        &iso_default("braintree.json", &iso),
    );
    singles(
        "klarna",
        "KLARNA",
        "Klarna's purchase currencies and their ISO 4217 exponents",
        &iso_default("klarna.json", &iso),
    );
    out.pop();
    out
}

#[test]
fn committed_tables_are_the_generators_output() {
    let path = root().join("rust/crates/ducat/src/processors/tables.rs");
    let generated = generate();
    if std::env::var_os("DUCAT_REGENERATE").is_some() {
        std::fs::write(&path, &generated).unwrap();
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == generated,
        "src/processors/tables.rs is stale: run `DUCAT_REGENERATE=1 cargo test -p ducat --test it processor_tables::`"
    );
}

// --- the public tables ---------------------------------------------------------------------------

/// A table as `(code, exponent, first multiple, second multiple)` rows, the multiples 1 where the
/// processor has none.
type Rows = Vec<(String, u64, u64, u64)>;

/// Every public table by processor, as [`Rows`].
fn public_tables() -> Vec<(&'static str, Rows)> {
    use ducat::processors::{adyen, braintree, checkout, klarna, paypal, stripe};
    let exponents = |table: &[ducat::processors::ExponentEntry]| -> Rows {
        table
            .iter()
            .map(|entry| (entry.code.to_owned(), u64::from(entry.exponent), 1, 1))
            .collect()
    };
    vec![
        (
            "stripe",
            stripe::rules()
                .iter()
                .map(|entry| {
                    let (code, exponent) = (entry.code.to_owned(), u64::from(entry.exponent));
                    (code, exponent, entry.charge_multiple, entry.payout_multiple)
                })
                .collect(),
        ),
        (
            "checkout",
            checkout::rules()
                .iter()
                .map(|entry| {
                    let (code, exponent) = (entry.code.to_owned(), u64::from(entry.exponent));
                    (code, exponent, entry.multiple, entry.standalone_multiple)
                })
                .collect(),
        ),
        ("adyen", exponents(adyen::exponents())),
        ("paypal", exponents(paypal::exponents())),
        ("braintree", exponents(braintree::exponents())),
        ("klarna", exponents(klarna::exponents())),
    ]
}

/// ducat's table from its generated module (`src/generated/<processor>.ts`, written by
/// scripts/gen-currencies.mjs): its `  CODE: [exponent,first,second],` or `  CODE: exponent,`
/// lines, in the file's order.
fn ducats_table(processor: &str) -> Rows {
    let path = root().join(format!("src/generated/{processor}.ts"));
    let text = std::fs::read_to_string(&path).unwrap();
    let (_, body) = text
        .split_once("> = {\n")
        .unwrap_or_else(|| panic!("{}: no table", path.display()));
    let (body, _) = body.split_once("\n};").unwrap();
    body.lines()
        .map(|line| {
            let (code, value) = line.trim().split_once(": ").unwrap();
            let value = value.trim_end_matches(',');
            let numbers: Vec<u64> = value
                .trim_start_matches('[')
                .trim_end_matches(']')
                .split(',')
                .map(|number| number.parse().unwrap())
                .collect();
            match numbers[..] {
                [exponent] => (code.to_owned(), exponent, 1, 1),
                [exponent, first, second] => (code.to_owned(), exponent, first, second),
                _ => panic!("{processor}: unexpected entry {line}"),
            }
        })
        .collect()
}

#[test]
fn public_tables_are_ducats_tables() {
    for (processor, table) in public_tables() {
        let mut ducat = ducats_table(processor);
        // ducat's are records, in the generator's order; Rust's are sorted for lookup
        ducat.sort();
        assert_eq!(table, ducat, "{processor}");
        assert!(table.is_sorted(), "{processor}: not sorted");
    }
}

#[test]
fn public_tables_are_the_spec_vectors_listed_currencies() {
    let path = root().join("spec/vectors/processors/rules.json");
    let vectors: Value = serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap();
    let rules = vectors["tables"]
        .as_array()
        .unwrap()
        .iter()
        .find(|table| table["op"] == "processor.rule")
        .unwrap();
    for (processor, table) in public_tables() {
        // the uppercase codes with a rule; the lowercase and unlisted ones test the lookups
        let listed: Rows = rules["rows"]
            .as_array()
            .unwrap()
            .iter()
            .filter(|row| row["processor"] == processor && !row["exponent"].is_null())
            .map(|row| {
                let code = row["currency"].as_str().unwrap().to_owned();
                (
                    code,
                    number(&row["exponent"]),
                    number(&row["multiple"]),
                    number(&row["contextMultiple"]),
                )
            })
            .filter(|row| row.0.bytes().all(|byte| byte.is_ascii_uppercase()))
            .collect();
        let mut sorted = listed.clone();
        sorted.sort();
        assert_eq!(table, sorted, "{processor}");
    }
}

#[test]
fn every_public_entry_is_its_lookup() {
    use ducat::processors::{adyen, braintree, checkout, klarna, paypal, stripe};
    for entry in stripe::rules() {
        assert_eq!(
            stripe::rule(entry.code),
            Some(entry.rule()),
            "{}",
            entry.code
        );
        let lower = entry.code.to_ascii_lowercase();
        assert_eq!(stripe::rule(&lower), Some(entry.rule()), "{lower}");
    }
    for entry in checkout::rules() {
        assert_eq!(
            checkout::rule(entry.code),
            Some(entry.rule()),
            "{}",
            entry.code
        );
        let lower = entry.code.to_ascii_lowercase();
        assert_eq!(checkout::rule(&lower), Some(entry.rule()), "{lower}");
    }
    for entry in adyen::exponents() {
        assert_eq!(
            adyen::rule(entry.code),
            Some(entry.exponent),
            "{}",
            entry.code
        );
        // Adyen's lookup is case-sensitive, as ducat's
        assert_eq!(
            adyen::rule(&entry.code.to_ascii_lowercase()),
            None,
            "{}",
            entry.code
        );
    }
    type Lookup = (
        fn(&str) -> Option<u8>,
        &'static [ducat::processors::ExponentEntry],
    );
    let lookups: [Lookup; 3] = [
        (paypal::rule, paypal::exponents()),
        (braintree::rule, braintree::exponents()),
        (klarna::rule, klarna::exponents()),
    ];
    for (rule, table) in lookups {
        for entry in table {
            assert_eq!(rule(entry.code), Some(entry.exponent), "{}", entry.code);
            let lower = entry.code.to_ascii_lowercase();
            assert_eq!(rule(&lower), Some(entry.exponent), "{lower}");
        }
    }
}
