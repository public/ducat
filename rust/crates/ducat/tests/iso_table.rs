//! The generator of `src/iso_table.rs`, and the check that the committed file is its output.
//!
//! The table comes from ISO 4217 List One
//! (`data/iso4217-list-one.xml`, at the repository's root). To regenerate it after updating that file:
//!
//! ```text
//! DUCAT_REGENERATE=1 cargo test -p ducat --test iso_table
//! ```

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../..")
}

/// The text of each `<tag>…</tag>` inside `entry`, the first one only.
fn element<'a>(entry: &'a str, tag: &str) -> Option<&'a str> {
    // `<Ccy>` or `<CcyNm IsFund="true">`, not `<Ccy` as a prefix of `<CcyNm>`
    let open = entry
        .find(&format!("<{tag}>"))
        .or_else(|| entry.find(&format!("<{tag} ")))?;
    let start = open + entry[open..].find('>')? + 1;
    let end = start + entry[start..].find(&format!("</{tag}>"))?;
    Some(entry[start..end].trim())
}

fn unescape(text: &str) -> String {
    text.replace("&apos;", "'")
        .replace("&quot;", "\"")
        .replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&amp;", "&")
}

/// `EUR` as a type name: `Eur`.
fn type_name(code: &str) -> String {
    let mut chars = code.chars();
    let first = chars.next().unwrap_or('X');
    let mut name = String::from(first);
    name.extend(chars.map(|c| c.to_ascii_lowercase()));
    name
}

fn generate() -> String {
    let xml = std::fs::read_to_string(root().join("data/iso4217-list-one.xml")).unwrap();
    let published = {
        let at = xml.find("Pblshd=\"").unwrap() + "Pblshd=\"".len();
        xml[at..at + 10].to_owned()
    };
    // code → (exponent or None for "N.A.", name); the first entry for a code gives its name
    let mut currencies: BTreeMap<String, (Option<u8>, String)> = BTreeMap::new();
    for entry in xml.split("<CcyNtry>").skip(1) {
        let entry = &entry[..entry.find("</CcyNtry>").unwrap()];
        let Some(code) = element(entry, "Ccy") else {
            continue;
        };
        let units = element(entry, "CcyMnrUnts").unwrap();
        let exponent = if units == "N.A." {
            None
        } else {
            Some(units.parse::<u8>().unwrap())
        };
        let name = unescape(element(entry, "CcyNm").unwrap());
        let previous = currencies
            .entry(code.to_owned())
            .or_insert((exponent, name));
        assert_eq!(previous.0, exponent, "{code} has two exponents");
    }
    assert!(
        currencies
            .keys()
            .all(|code| code.len() == 3 && code.bytes().all(|b| b.is_ascii_uppercase()))
    );

    let monetary: Vec<_> = currencies
        .iter()
        .filter_map(|(code, (exponent, name))| Some((code, (*exponent)?, name)))
        .collect();
    let non_monetary: Vec<_> = currencies
        .iter()
        .filter(|(_, (exponent, _))| exponent.is_none())
        .map(|(code, _)| code)
        .collect();

    let mut out = String::new();
    writeln!(
        out,
        "// GENERATED by rust/crates/ducat/tests/iso_table.rs from data/iso4217-list-one.xml."
    )
    .unwrap();
    writeln!(
        out,
        "// Do not edit by hand: run `DUCAT_REGENERATE=1 cargo test -p ducat --test iso_table`."
    )
    .unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "/// The publication date of the ISO 4217 List One snapshot the table comes from."
    )
    .unwrap();
    writeln!(out, "pub const ISO_4217_PUBLISHED: &str = \"{published}\";").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "/// Every active ISO 4217 code with a minor unit ({} codes), sorted: code, exponent, name.", monetary.len()).unwrap();
    writeln!(
        out,
        "pub(crate) const ISO_EXPONENTS: [(&str, u8, &str); {}] = [",
        monetary.len()
    )
    .unwrap();
    for (code, exponent, name) in &monetary {
        writeln!(out, "    ({code:?}, {exponent}, {name:?}),").unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "/// The active codes whose minor unit ISO lists as \"N.A.\" (XAU, XDR, XTS…)."
    )
    .unwrap();
    writeln!(
        out,
        "pub(crate) const NON_MONETARY: [&str; {}] = [",
        non_monetary.len()
    )
    .unwrap();
    for code in &non_monetary {
        writeln!(out, "    {code:?},").unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#[cfg(feature = \"iso\")]").unwrap();
    writeln!(out, "iso_markers! {{").unwrap();
    for (code, exponent, name) in &monetary {
        writeln!(
            out,
            "    {} = {code:?}, {exponent}, {:?};",
            type_name(code),
            format!("{name} ({code}), exponent {exponent}.")
        )
        .unwrap();
    }
    writeln!(out, "}}").unwrap();
    out
}

#[test]
fn committed_table_is_the_generators_output() {
    let path = root().join("rust/crates/ducat/src/iso_table.rs");
    let generated = generate();
    if std::env::var_os("DUCAT_REGENERATE").is_some() {
        std::fs::write(&path, &generated).unwrap();
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == generated,
        "src/iso_table.rs is stale: run `DUCAT_REGENERATE=1 cargo test -p ducat --test iso_table`"
    );
}
